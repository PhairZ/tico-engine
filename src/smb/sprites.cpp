#include "sprites.h"

Sprites::SpriteMap Sprites::get_tile_at_pos(Vector2I p_pos) {
	if (p_pos.x <= 0 || p_pos.x >= Sprites::C_MAP_SIZE.x * 16 || p_pos.y <= 0 || p_pos.y >= Sprites::C_MAP_SIZE.y * 16) {
		return Sprites::SPRITE_NULL;
	}

	Vector2I tile_pos = p_pos / 16;
	int tile = tile_pos.y * Sprites::C_MAP_SIZE.x + tile_pos.x;

	return (Sprites::SpriteMap)Sprites::map_data[tile];
}

void Sprites::set_tile_at_pos(Vector2I p_pos, Sprites::SpriteMap p_tile) {
	if (p_pos.x <= 0 || p_pos.x >= Sprites::C_MAP_SIZE.x * 16 || p_pos.y <= 0 || p_pos.y >= Sprites::C_MAP_SIZE.y * 16) {
		return;
	}

	Vector2I tile_pos = p_pos / 16;
	int tile = tile_pos.y * Sprites::C_MAP_SIZE.x + tile_pos.x;
	Sprites::map_data[tile] = (char)p_tile;
}

